// Keeps the Tranco ranking (and the look-alike index built from it) in memory.
//
// Where the list comes from, newest first:
//   1. data/feeds/tranco/: lists this server generated through the Tranco API
//      (needs TRANCO_API_EMAIL and TRANCO_API_KEY), refreshed every few days
//   2. assets/tranco/: the snapshot bundled in the image (BUNDLED_TRANCO_LIST_ID)
//
// Fail safe: with no list, or only one whose data is more than 7 days old,
// look-alike detection is skipped with the reason. It never falls back to
// flagging everything or to a hand-kept brand list. A refresh that fails
// keeps the current list while it is still within the 7 days.
import fs from 'fs';
import path from 'path';
import zlib from 'zlib';
import { buildBrandIndex, type BrandIndex } from '@/lib/lookalike/detect';
import { parseRanking } from '@/lib/lookalike/ranking';
import {
  TRANCO_MAX_AGE_DAYS,
  TRANCO_ROWS,
  configurationProblem,
  listAgeDays,
  trancoConfiguration,
  type TrancoListMeta,
} from '@/lib/lookalike/tranco-list';

const API = 'https://tranco-list.eu/api';
const DAY_MS = 86_400_000;
/** Generate a new list once the current one's data is this old */
const REFRESH_AFTER_DAYS = 3;
/** Wait this long after a failed refresh before trying again */
const RETRY_AFTER_MS = 6 * 60 * 60 * 1000;
/** Tranco queues list generation; give up waiting after this */
const GENERATE_TIMEOUT_MS = 30 * 60 * 1000;
const REQUEST_TIMEOUT_MS = 30_000;

export type BrandIndexState =
  | { ok: true; index: BrandIndex; list: TrancoListMeta; ageDays: number }
  | { ok: false; reason: string };

export interface TrancoStoreDeps {
  fetch?: typeof fetch;
  now?: () => number;
  /** Lists generated by this server (on the data volume) */
  cacheDir?: string;
  /** The bundled snapshot (in the image) */
  bundleDir?: string;
  credentials?: { email: string; key: string } | null;
  pollMs?: number;
  /** A downloaded list shorter than this is treated as broken */
  minRows?: number;
  log?: (message: string) => void;
}

interface Loaded {
  meta: TrancoListMeta;
  index: BrandIndex;
}

class RefreshError extends Error {}

function readJson<T>(file: string): T | null {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8')) as T;
  } catch {
    return null;
  }
}

export function createTrancoStore(deps: TrancoStoreDeps = {}) {
  const fetchFn = deps.fetch ?? fetch;
  const now = deps.now ?? Date.now;
  const cacheDir = deps.cacheDir ?? path.join(process.env.FEEDS_DIR?.trim() || path.join(process.cwd(), 'data', 'feeds'), 'tranco');
  const bundleDir = deps.bundleDir ?? path.join(process.cwd(), 'assets', 'tranco');
  const credentials = deps.credentials === undefined ? envCredentials() : deps.credentials;
  const pollMs = deps.pollMs ?? 15_000;
  const minRows = deps.minRows ?? 50_000;
  const log = deps.log ?? ((message: string) => console.warn(`Tranco: ${message}`));

  let current: Loaded | null = null;
  let loadedFromDisk = false;
  let refreshing: Promise<void> | null = null;
  let lastAttempt = 0;
  let lastError: string | null = null;

  /** A list on disk: `dir/manifest.json` (or current.json) next to its CSV (plain or .gz) */
  function loadFrom(dir: string, manifestName: string): Loaded | null {
    const meta = readJson<TrancoListMeta & { file?: string }>(path.join(dir, manifestName));
    if (!meta?.listId || !meta.endDate || !meta.file) return null;
    try {
      const raw = fs.readFileSync(path.join(dir, meta.file));
      const text = meta.file.endsWith('.gz') ? zlib.gunzipSync(raw).toString('utf8') : raw.toString('utf8');
      const ranking = parseRanking(text);
      if (ranking.length < Math.min(minRows, meta.rows)) throw new Error(`only ${ranking.length} rows`);
      const problem = configurationProblem({ providers: meta.providers, filterPLD: 'on' });
      if (problem) throw new Error(`list ${meta.listId} can't be used: ${problem}`);
      const { file, ...rest } = meta;
      void file;
      return { meta: rest, index: buildBrandIndex(ranking) };
    } catch (error) {
      log(`could not load ${path.join(dir, meta.file)}: ${(error as Error).message}`);
      return null;
    }
  }

  function loadLocal(): Loaded | null {
    const candidates = [loadFrom(cacheDir, 'current.json'), loadFrom(bundleDir, 'manifest.json')].filter((c): c is Loaded => c !== null);
    candidates.sort((a, b) => b.meta.endDate.localeCompare(a.meta.endDate));
    return candidates[0] ?? null;
  }

  async function api(url: string, init: RequestInit = {}): Promise<Response> {
    const headers: Record<string, string> = { 'User-Agent': 'osint-analyzer/1.0 (+look-alike detection)' };
    if (credentials) headers.Authorization = `Basic ${Buffer.from(`${credentials.email}:${credentials.key}`).toString('base64')}`;
    const response = await fetchFn(url, { ...init, headers: { ...headers, ...(init.headers as Record<string, string>) }, signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS) });
    if (!response.ok) throw new RefreshError(`${init.method ?? 'GET'} ${url.replace(API, '')}: HTTP ${response.status}`);
    return response;
  }

  async function generate(): Promise<void> {
    if (!credentials) throw new RefreshError('no TRANCO_API_EMAIL / TRANCO_API_KEY');
    const endDate = new Date(now() - DAY_MS).toISOString().slice(0, 10);
    const config = trancoConfiguration(endDate);
    const created = (await (await api(`${API}/lists/create`, {
      method: 'PUT',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(config),
    })).json()) as { list_id?: string };
    const listId = created.list_id;
    if (!listId) throw new RefreshError('Tranco did not return a list ID');

    // Generation is queued; poll until the list is ready
    const deadline = now() + GENERATE_TIMEOUT_MS;
    type Info = { available?: boolean; failed?: boolean; created_on?: string; configuration?: { providers?: string[]; startDate?: string; endDate?: string; filterPLD?: string } };
    let info = (await (await api(`${API}/lists/id/${listId}`)).json()) as Info;
    while (!info.available) {
      if (info.failed) throw new RefreshError(`Tranco failed to generate list ${listId}`);
      if (now() > deadline) throw new RefreshError(`list ${listId} still not ready after ${GENERATE_TIMEOUT_MS / 60_000} minutes`);
      await new Promise((r) => setTimeout(r, pollMs));
      info = (await (await api(`${API}/lists/id/${listId}`)).json()) as Info;
    }
    const problem = configurationProblem(info.configuration);
    if (problem) throw new RefreshError(`list ${listId} can't be used: ${problem}`);

    const text = await (await api(`https://tranco-list.eu/download/${listId}/${TRANCO_ROWS}`)).text();
    const ranking = parseRanking(text);
    if (ranking.length < minRows) throw new RefreshError(`list ${listId} has only ${ranking.length} rows`);

    const meta: TrancoListMeta = {
      listId,
      startDate: info.configuration?.startDate ?? config.startDate,
      endDate: info.configuration?.endDate ?? config.endDate,
      providers: info.configuration?.providers ?? config.providers,
      rows: ranking.length,
      createdOn: info.created_on ?? null,
    };
    const index = buildBrandIndex(ranking);
    fs.mkdirSync(cacheDir, { recursive: true });
    const file = `tranco-${listId}.csv`;
    fs.writeFileSync(path.join(cacheDir, `${file}.tmp`), text);
    fs.renameSync(path.join(cacheDir, `${file}.tmp`), path.join(cacheDir, file));
    fs.writeFileSync(path.join(cacheDir, 'current.json'), JSON.stringify({ ...meta, file }, null, 2));
    // Older generated lists are no longer needed
    for (const old of fs.readdirSync(cacheDir)) {
      if (/^tranco-.+\.csv$/.test(old) && old !== file) fs.rmSync(path.join(cacheDir, old), { force: true });
    }
    current = { meta, index };
  }

  /** Generate and load a new list now. Never throws; the error is kept for the skip reason. */
  function refresh(): Promise<void> {
    if (refreshing) return refreshing;
    lastAttempt = now();
    refreshing = generate()
      .then(() => {
        lastError = null;
      })
      .catch((error) => {
        lastError = error instanceof RefreshError ? error.message : `could not reach Tranco (${(error as Error).message})`;
        log(`refresh failed: ${lastError}`);
      })
      .finally(() => {
        refreshing = null;
      });
    return refreshing;
  }

  function ensureLoaded() {
    if (loadedFromDisk) return;
    loadedFromDisk = true;
    current = loadLocal();
  }

  /** The current index, or why look-alike detection has to be skipped. Never waits for a download. */
  function get(): BrandIndexState {
    ensureLoaded();
    const age = current ? listAgeDays(current.meta, now()) : null;
    const due = age === null || age >= REFRESH_AFTER_DAYS;
    if (due && credentials && !refreshing && now() - lastAttempt > RETRY_AFTER_MS) void refresh();

    if (current && age !== null && age <= TRANCO_MAX_AGE_DAYS) return { ok: true, index: current.index, list: current.meta, ageDays: age };

    const why = lastError ? ` Last refresh failed: ${lastError}.` : !credentials ? ' This server has no Tranco API key to refresh it.' : '';
    if (refreshing && !current) return { ok: false, reason: 'The popularity list is still downloading. Not counted in the score.' };
    if (!current) return { ok: false, reason: `No popularity list available.${why} Not counted in the score.` };
    return {
      ok: false,
      reason: `The popularity list (Tranco ${current.meta.listId}, data to ${current.meta.endDate}) is ${age} days old; look-alike checks need one under ${TRANCO_MAX_AGE_DAYS} days.${why} Not counted in the score.`,
    };
  }

  return { get, refresh, status: () => ({ list: current?.meta ?? null, lastError, refreshing: refreshing !== null }) };
}

function envCredentials(): { email: string; key: string } | null {
  const email = process.env.TRANCO_API_EMAIL?.trim();
  const key = process.env.TRANCO_API_KEY?.trim();
  return email && key ? { email, key } : null;
}

const globalForTranco = globalThis as unknown as { __osintTranco?: ReturnType<typeof createTrancoStore> };

function store() {
  return (globalForTranco.__osintTranco ??= createTrancoStore());
}

/** The look-alike index for analyses (see BrandIndexState) */
export function brandIndex(): BrandIndexState {
  return store().get();
}

/** Load the list (and start a refresh if one is due) before a bulk job */
export function preloadBrandIndex(): void {
  store().get();
}
